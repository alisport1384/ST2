package com.alisport.goldpin.core

// ═══════════════════════════════════════════════════════════════════════════════
//  پارامترهای «تنظیم‌شده با داده» (Tuned) — جای پیش‌فرض‌های کاغذی سند، وقتی پای
//  کارمزد واقعی در میان است.
//
//  نسخهٔ ۲ (۱٫۴٫۴۶) — تنظیم روی دادهٔ واقعی **ده‌ساله** (۳٬۴۰۲٬۱۲۶ کندل M1 طلا،
//  ۲۰۱۶-۰۸-۲۱ تا ۲۰۲۶-۰۸-۲۰، فایل `datasets/goldpin_xauusd_m1_10y.csv.gz` در مخزن)
//  با کارمزد ۰٫۷ دلار. روش: جست‌وجو روی پنجرهٔ آموزش ۲۰۱۶–۲۰۲۲، اعتبارسنجی روی
//  پنجرهٔ نگه‌داشته‌شدهٔ ۲۰۲۳–۲۰۲۶، و عدد نهایی روی کل دهه (گزارش: `sweep/`).
//
//  چرا نسخهٔ ۱ (بهینهٔ یک‌ساله: بافر ۲۰۰ تیک) کنار رفت:
//  همان تنظیم روی ده سال در **تک‌تک سال‌ها** ضرر داد (مجموع ‎−۲۰٬۵۸۷$‎، ضریب سود
//  ۰٫۷۹۵) — یعنی برازش روی رژیم ۲۰۲۵-۲۶ بود، نه لبهٔ پایدار. منحنی بافر روی هر دو
//  پنجرهٔ آموزش و آزمون یکنواخت صعودی بود تا حوالی ۹۰۰ تیک و بعد صاف می‌شد.
//
//  نتیجهٔ اندازه‌گیری‌شدهٔ این نسخه (استراتژی ۱ · Mixed · کارمزد ۰٫۷):
//    کل ده سال   → ۲٬۶۸۵ معامله · نرخ برد ۴۲٫۷٪ · انتظار ‎−۰٫۰۱۳R‎ · خالص ‎−۱٬۲۶۴$‎ ·
//                  ضریب سود ۰٫۹۹۰ · بیشترین افت ‎۹٬۵۰۲$‎ · ۴۸ ماه مثبت از ۱۲۱
//    ۲۰۲۳–۲۰۲۶ (نگه‌داشته‌شده، در تنظیم دخیل نبود) → ‎+۰٫۰۲۲R‎ · ‎+۴٬۳۲۷$‎ · ضریب سود ۱٫۰۶۱
//    سال آخر داده (۲۰۲۵-۰۸ تا ۲۰۲۶-۰۸) → ‎+۰٫۰۸۹R‎ · ‎+۴٬۸۷۸$‎ · ضریب سود ۱٫۱۶۰
//  مقایسه: پیش‌فرض سند ۷ روی ده سال **صفر سفارش** می‌دهد (فیلتر ۶×۰٫۷=۴٫۲ > سقف ۳).
//
//  ⚠ صادقانه: روی ۲۰۱۶–۲۰۲۲ این تنظیم هنوز ‎−۰٫۰۴۲R‎ است؛ یعنی لبهٔ این استراتژی با
//  کارمزد ۰٫۷ عمدتاً در رژیم پرنوسانِ سال‌های اخیر وجود دارد و «سود تضمینی» نیست.
//  عدد ده‌ساله تقریباً سربه‌سر است؛ بهبودش نسبت به نسخهٔ قبل از ‎−۲۰٬۵۸۷$‎ به
//  ‎−۱٬۲۶۴$‎ و مثبت‌شدن پنجرهٔ نگه‌داشته‌شده است. اگر کارمزد کاربر فرق دارد، بخش
//  «تطبیق» در اپ آستانه‌ها را از روی کارمزد او دوباره می‌سازد.
// ═══════════════════════════════════════════════════════════════════════════════

object Tuned {

    /** کارمزد/اسپرد مرجع (واحد قیمت) که این تنظیم با آن آزموده شده است. */
    const val CMSN = 0.7

    /** هدف تریگر ۲ بر حسب R. */
    const val TARGET_R = 7.0

    /** بافر حد ضرر به تیک (× mintick ⇒ ۹٫۰۰ دلار فاصلهٔ اضافه از لبهٔ باکس). */
    const val SL_BUF_TICKS = 900.0

    /** بافر سطح سفارش به تیک؛ منفی یعنی چند تیک **داخل** باکس (پیشنهاد §۴-۳ گزارش ورود). */
    const val ENTRY_BUF_TICKS = -2.0

    /** سقف فاصلهٔ حد ضرر N (§18-31) — باید از فاصلهٔ جدید حد ضرر بزرگ‌تر باشد. */
    const val MAX_SL_UNITS = 40.0

    /** ضریب فیلتر کارمزد §۵-۳: با حد ضرر پهن، خاموش است (خودِ حد ضرر هزینه را پوشش می‌دهد). */
    const val COST_MULT = 0.0

    /** جهت معامله: هم‌جهت با ساختار (معکوس خاموش). در این سال، معکوس منفی بود. */
    const val TRIGGER2_FADE = false

    /**
     * اعمال تنظیم آزموده‌شده روی [c]. فقط همان کلیدهایی را عوض می‌کند که در جاروب
     * اثرگذار بودند؛ بقیهٔ تنظیمات کاربر (تایم‌فریم، ریسک، مدیریت مالی…) دست‌نخورده می‌ماند.
     */
    fun apply(c: Settings, cmsn: Double = CMSN) {
        c.trigger2Fade = TRIGGER2_FADE
        c.trigger2TargetR = TARGET_R
        c.slBufTicks = SL_BUF_TICKS
        c.entryBufTicks = ENTRY_BUF_TICKS
        c.maxSlUnits = MAX_SL_UNITS
        c.minSlUnits = 0.0
        c.minSlCostMult = COST_MULT
        // [cmsn] صفر یا منفی ⇒ «کارمزد را دست نزن»: هندسهٔ استراتژی تنظیم می‌شود ولی مبنای
        // کارمزد همان می‌ماند که کاربر/بروکر دارد (اسپرد خودکار معقول یا عدد دستی خودش).
        if (cmsn > 0.0) {
            c.cmsnAuto = false
            c.cmsnManual = cmsn
        }
    }

    /**
     * آیا این تنظیمات دقیقاً همان پیش‌فرض‌های دست‌نخوردهٔ سند ۷ (نسخهٔ ۱٫۴٫۳۶ تا ۱٫۴٫۴۱) است؟
     *
     * فقط در این حالت مهاجرت `specRev=9` مقدارها را عوض می‌کند؛ اگر کاربر حتی یکی را
     * دست‌کاری کرده باشد، انتخابش محترم می‌ماند (همان قاعدهٔ مهاجرت‌های قبلی).
     */
    /**
     * آیا این تنظیمات دقیقاً همان خروجی نسخهٔ ۱ این تنظیم است (نسخه‌های ۱٫۴٫۴۲ تا
     * ۱٫۴٫۴۵: هم‌جهت · هدف ۷R · بافر ۲۰۰ · بافر سفارش ‎−۲‎ · N=۱۰ · فیلتر خاموش)؟
     *
     * فقط در این حالت مهاجرت `specRev=10` مقدارها را به نسخهٔ ۲ می‌برد؛ هر انحرافی
     * یعنی کاربر دستی عوض کرده و انتخابش دست‌نخورده می‌ماند.
     */
    fun isUntouchedTunedV1(c: Settings): Boolean =
        !c.trigger2Fade && c.trigger2TargetR == 7.0 && c.minSlCostMult == 0.0 &&
            c.slBufTicks == 200.0 && c.entryBufTicks == -2.0 && c.maxSlUnits == 10.0 &&
            c.minSlUnits == 0.0

    fun isUntouchedDoc7(c: Settings): Boolean =
        c.trigger2Fade && c.trigger2TargetR == 4.0 && c.minSlCostMult == 6.0 &&
            c.slBufTicks == 2.0 && c.entryBufTicks == 1.0 && c.maxSlUnits == 3.0 &&
            c.minSlUnits == 0.0
}
